/**
 * Builds src/styles/tokens.css, src/styles/palettes.ts and src/styles/feedback.ts from
 * tokens/tokens.json, the master copy of every design decision: colors, type, spacing,
 * corners, shadows, motion, and sound and haptics. Figma's variables come from the same file.
 *
 * Run with: npm run tokens
 *
 * How the CSS picks colors:
 * - <html data-theme="light|dark"> forces a theme; with no attribute the system setting decides.
 * - <html data-palette="berry"> picks a palette; with no attribute it is Bodai.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Colors = Record<string, string>;
type TypeStyle = {
  size: number;
  line: number;
  weight: number;
  tracking: number;
  case?: 'upper';
  use: string;
};
type Tokens = {
  theme: { light: Colors; dark: Colors };
  palettes: Record<string, { light: Colors; dark: Colors }>;
  shape: Record<string, number | string>;
  space: Record<string, number | string>;
  type: { family: string; styles: Record<string, TypeStyle> };
  elevation: Record<string, string>;
  motion: Record<string, number | string>;
  feedback: Record<string, unknown>;
};

/** Entries of a token group, without its $description. */
const entries = <T>(group: Record<string, T>) =>
  Object.entries(group).filter(([name]) => !name.startsWith('$'));

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens: Tokens = JSON.parse(readFileSync(join(ROOT, 'tokens/tokens.json'), 'utf8'));
const palettes = Object.entries(tokens.palettes).filter(([name]) => !name.startsWith('$'));
const shape = entries(tokens.shape);
const [defaultName, defaultPalette] = palettes[0]!;

const declare = (colors: Colors, indent = '  ') =>
  Object.entries(colors)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n');

/** One selector block per dark rule: the system setting, and the explicit toggle. */
const darkSelectors = (suffix = '') => [
  `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light'])${suffix} {`,
  `:root[data-theme='dark']${suffix} {`,
];

function darkBlock(colors: Colors, suffix = ''): string {
  const [media, explicit] = darkSelectors(suffix);
  return [
    `${media}\n    color-scheme: dark;\n${declare(colors, '    ')}\n  }\n}`,
    `${explicit}\n  color-scheme: dark;\n${declare(colors)}\n}`,
  ].join('\n\n');
}

const colorNames = [...Object.keys(tokens.theme.light), ...Object.keys(defaultPalette.light)];

const css = `/*
 * GENERATED by \`npm run tokens\` from tokens/tokens.json. Do not edit by hand.
 */

:root {
  color-scheme: light;
${declare(tokens.theme.light)}
${declare(defaultPalette.light)}
${shape.map(([name, value]) => `  --${name}: ${value}px;`).join('\n')}
}

${darkBlock({ ...tokens.theme.dark, ...defaultPalette.dark })}

/* Palettes */
${palettes
  .slice(1)
  .map(
    ([name, palette]) =>
      `:root[data-palette='${name}'] {\n${declare(palette.light)}\n}\n\n${darkBlock(palette.dark, `[data-palette='${name}']`)}`,
  )
  .join('\n\n')}

/* Expose every token to Tailwind, so \`bg-surface\`, \`text-ink\`, \`rounded-md\` work. */
@theme inline {
${colorNames.map((name) => `  --color-${name}: var(--${name});`).join('\n')}
${shape.map(([name]) => `  --radius-${name.replace('corner-', '')}: var(--${name});`).join('\n')}
}

/* Type, shadows and easing. \`static\` keeps every variable in the CSS, used or not. */
@theme static {
${entries(tokens.type.styles)
  .map(
    ([name, t]) =>
      `  --text-${name}: ${t.size}px;\n  --text-${name}--line-height: ${t.line}px;\n  --text-${name}--font-weight: ${t.weight};\n  --text-${name}--letter-spacing: ${t.tracking}em;`,
  )
  .join('\n')}
${entries(tokens.elevation)
  .map(([name, value]) => `  --${name}: ${value};`)
  .join('\n')}
${entries(tokens.motion)
  .filter(([name]) => name.startsWith('ease-'))
  .map(([name, value]) => `  --${name}: ${value};`)
  .join('\n')}
}

/*
 * Spacing and durations. Spacing matches Tailwind's 4px scale, so use its numbers:
 * xs = 1 (4px), sm = 2, md = 3, lg = 4, xl = 6, 2xl = 8, 3xl = 12.
 */
:root {
${entries(tokens.space)
  .map(([name, value]) => `  --space-${name}: ${value}px;`)
  .join('\n')}
${entries(tokens.motion)
  .filter(([name]) => name.startsWith('duration-'))
  .map(([name, value]) => `  --${name}: ${value}ms;`)
  .join('\n')}
}

/* Type styles that also set letter case. Use with the matching text-* class. */
${entries(tokens.type.styles)
  .filter(([, t]) => t.case === 'upper')
  .map(([name]) => `.text-${name} {\n  text-transform: uppercase;\n}`)
  .join('\n\n')}
`;

const ts = `// GENERATED by \`npm run tokens\` from tokens/tokens.json. Do not edit by hand.

export const PALETTES = ${JSON.stringify(palettes.map(([name]) => name))} as const;
export type Palette = (typeof PALETTES)[number];
export const DEFAULT_PALETTE: Palette = '${defaultName}';

/** Each palette's accent color, for swatches in the palette picker. */
export const PALETTE_SWATCHES: Record<Palette, string> = ${JSON.stringify(Object.fromEntries(palettes.map(([name, p]) => [name, p.light.accent])))};
`;

writeFileSync(join(ROOT, 'src/styles/tokens.css'), css);
writeFileSync(join(ROOT, 'src/styles/palettes.ts'), ts);
writeFileSync(
  join(ROOT, 'src/styles/feedback.ts'),
  `// GENERATED by \`npm run tokens\` from tokens/tokens.json. Do not edit by hand.

export type Haptic = 'tap' | 'error' | 'win';
export type Sound =
  | { tone: number[]; length: number; volume: number; wave?: OscillatorType }
  | { sample: string };
export type Feedback = { sound: Sound | null; haptic: Haptic | null; note: string };

/** What the player hears and feels for each moment in the game. */
export const FEEDBACK = ${JSON.stringify((tokens.feedback as { events: unknown }).events, null, 2)} as const satisfies Record<string, Feedback>;

export type FeedbackEvent = keyof typeof FEEDBACK;
`,
);
console.log(
  `Built ${colorNames.length} color tokens, ${palettes.length} palettes, ${shape.length} shape tokens.`,
);
