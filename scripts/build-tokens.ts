/**
 * Builds src/styles/tokens.css and src/styles/palettes.ts from tokens/tokens.json,
 * the master copy of every color. Figma's variables are made from the same file.
 *
 * Run with: npm run tokens
 *
 * How the CSS picks colors:
 * - <html data-theme="light|dark"> forces a theme; with no attribute the system setting decides.
 * - <html data-palette="berry"> picks a palette; with no attribute it is Bodai.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Colors = Record<string, string>;
type Tokens = {
  theme: { light: Colors; dark: Colors };
  palettes: Record<string, { light: Colors; dark: Colors }>;
  shape: Record<string, number | string>;
};

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens: Tokens = JSON.parse(readFileSync(join(ROOT, 'tokens/tokens.json'), 'utf8'));
const palettes = Object.entries(tokens.palettes).filter(([name]) => !name.startsWith('$'));
const shape = Object.entries(tokens.shape).filter(([name]) => !name.startsWith('$'));
const [defaultName, defaultPalette] = palettes[0]!;

const declare = (colors: Colors, indent = '  ') =>
  Object.entries(colors)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n');

/** One selector block per dark rule: the system setting, and the explicit toggle. */
const darkSelectors = (suffix = '') => [
  `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light'])${suffix} {`,
  `:root[data-theme='dark']${suffix} {`,
];

function darkBlock(colors: Colors, suffix = ''): string {
  const [media, explicit] = darkSelectors(suffix);
  return [
    `${media}\n    color-scheme: dark;\n${declare(colors, '    ')}\n  }\n}`,
    `${explicit}\n  color-scheme: dark;\n${declare(colors)}\n}`,
  ].join('\n\n');
}

const colorNames = [...Object.keys(tokens.theme.light), ...Object.keys(defaultPalette.light)];

const css = `/*
 * GENERATED by \`npm run tokens\` from tokens/tokens.json. Do not edit by hand.
 */

:root {
  color-scheme: light;
${declare(tokens.theme.light)}
${declare(defaultPalette.light)}
${shape.map(([name, value]) => `  --${name}: ${value}px;`).join('\n')}
}

${darkBlock({ ...tokens.theme.dark, ...defaultPalette.dark })}

/* Palettes */
${palettes
  .slice(1)
  .map(
    ([name, palette]) =>
      `:root[data-palette='${name}'] {\n${declare(palette.light)}\n}\n\n${darkBlock(palette.dark, `[data-palette='${name}']`)}`,
  )
  .join('\n\n')}

/* Expose every token to Tailwind, so \`bg-surface\`, \`text-ink\`, \`rounded-md\` work. */
@theme inline {
${colorNames.map((name) => `  --color-${name}: var(--${name});`).join('\n')}
${shape.map(([name]) => `  --radius-${name.replace('corner-', '')}: var(--${name});`).join('\n')}
}
`;

const ts = `// GENERATED by \`npm run tokens\` from tokens/tokens.json. Do not edit by hand.

export const PALETTES = ${JSON.stringify(palettes.map(([name]) => name))} as const;
export type Palette = (typeof PALETTES)[number];
export const DEFAULT_PALETTE: Palette = '${defaultName}';

/** Each palette's accent color, for swatches in the palette picker. */
export const PALETTE_SWATCHES: Record<Palette, string> = ${JSON.stringify(Object.fromEntries(palettes.map(([name, p]) => [name, p.light.accent])))};
`;

writeFileSync(join(ROOT, 'src/styles/tokens.css'), css);
writeFileSync(join(ROOT, 'src/styles/palettes.ts'), ts);
console.log(
  `Built ${colorNames.length} color tokens, ${palettes.length} palettes, ${shape.length} shape tokens.`,
);
