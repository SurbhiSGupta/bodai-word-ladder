/**
 * Writes tokens/figma-sync.js: a Figma Plugin API script that creates or updates the
 * design system's variables from tokens/tokens.json. Claude runs it through the Figma
 * connector (use_figma), so Figma always matches the code. Safe to run again: it finds
 * existing collections, modes and variables by name and only updates their values.
 *
 * Run with: npm run figma-sync
 *
 * Figma structure:
 * - "Palette" collection, one mode per palette (Bodai, Berry...). Holds each palette's
 *   light/… and dark/… colors. Hidden from pickers; Theme points at it.
 * - "Theme" collection, modes Light and Dark. Every color a designer uses. Palette-driven
 *   colors (accent, highlight…) are aliases into Palette, so switching Theme and Palette
 *   modes independently works just like the app.
 * - "Shape" collection, one mode. Corner radii.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(ROOT, 'tokens/tokens.json'), 'utf8'));

const script = `// GENERATED by \`npm run figma-sync\` from tokens/tokens.json. Do not edit by hand.
const T = ${JSON.stringify(tokens)};
const skip = (k) => k.startsWith('$');
const title = (s) => s[0].toUpperCase() + s.slice(1);
function rgba(hex) {
  const h = hex.replace('#', '');
  const n = parseInt(h.slice(0, 6), 16);
  return { r: ((n >> 16) & 255) / 255, g: ((n >> 8) & 255) / 255, b: (n & 255) / 255, a: h.length === 8 ? parseInt(h.slice(6), 16) / 255 : 1 };
}
const collections = await figma.variables.getLocalVariableCollectionsAsync();
const variables = await figma.variables.getLocalVariablesAsync();
const touched = [];

function collection(name, modeNames) {
  let c = collections.find((x) => x.name === name);
  if (!c) c = figma.variables.createVariableCollection(name);
  const ids = {};
  modeNames.forEach((m, i) => {
    let mode = c.modes.find((x) => x.name === m);
    if (!mode && i === 0 && c.modes.length === 1 && !modeNames.includes(c.modes[0].name)) {
      c.renameMode(c.modes[0].modeId, m);
      mode = c.modes[0];
    }
    ids[m] = mode ? mode.modeId : c.addMode(m);
  });
  return { c, ids };
}
function variable(c, name, type, scopes, cssName) {
  let v = variables.find((x) => x.name === name && x.variableCollectionId === c.id);
  if (!v) v = figma.variables.createVariable(name, c, type);
  v.scopes = scopes;
  if (cssName) v.setVariableCodeSyntax('WEB', 'var(--' + cssName + ')');
  touched.push(v.id);
  return v;
}
function scopesFor(name) {
  if (name === 'edge') return ['STROKE_COLOR'];
  if (name === 'ink' || name === 'muted' || name.endsWith('-ink')) return ['TEXT_FILL', 'SHAPE_FILL', 'STROKE_COLOR'];
  return ['FRAME_FILL', 'SHAPE_FILL'];
}

// Palette: one mode per palette, light/* and dark/* variables.
const paletteNames = Object.keys(T.palettes).filter((k) => !skip(k));
const palette = collection('Palette', paletteNames.map(title));
const paletteVars = {};
for (const themeName of ['light', 'dark']) {
  for (const key of Object.keys(T.palettes[paletteNames[0]][themeName])) {
    const v = variable(palette.c, themeName + '/' + key, 'COLOR', [], null);
    for (const p of paletteNames) v.setValueForMode(palette.ids[title(p)], rgba(T.palettes[p][themeName][key]));
    paletteVars[themeName + '/' + key] = v;
  }
}

// Theme: Light and Dark.
const theme = collection('Theme', ['Light', 'Dark']);
for (const key of Object.keys(T.theme.light)) {
  const v = variable(theme.c, 'color/' + key, 'COLOR', scopesFor(key), key);
  v.setValueForMode(theme.ids.Light, rgba(T.theme.light[key]));
  v.setValueForMode(theme.ids.Dark, rgba(T.theme.dark[key]));
}
for (const key of Object.keys(T.palettes[paletteNames[0]].light)) {
  const v = variable(theme.c, 'color/' + key, 'COLOR', scopesFor(key), key);
  v.setValueForMode(theme.ids.Light, { type: 'VARIABLE_ALIAS', id: paletteVars['light/' + key].id });
  v.setValueForMode(theme.ids.Dark, { type: 'VARIABLE_ALIAS', id: paletteVars['dark/' + key].id });
}

// Shape: corner radii.
const shape = collection('Shape', ['Value']);
for (const [key, value] of Object.entries(T.shape).filter(([k]) => !skip(k))) {
  const v = variable(shape.c, 'radius/' + key.replace('corner-', ''), 'FLOAT', ['CORNER_RADIUS'], key);
  v.setValueForMode(shape.ids.Value, Number(value));
}

return {
  collections: { Palette: palette.c.id, Theme: theme.c.id, Shape: shape.c.id },
  modes: { Palette: palette.ids, Theme: theme.ids },
  variableCount: touched.length,
};
`;

writeFileSync(join(ROOT, 'tokens/figma-sync.js'), script);
console.log('Wrote tokens/figma-sync.js');
